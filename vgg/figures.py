"""
Every figure in this folder, rendered from results/*.json.

Nothing here measures anything. The measuring is done by vgg.py, cost.py,
init_study.py, dense_eval.py and analysis.py, each of which writes its numbers
to results/. This script only draws them.

That separation is the point. It means the figures can be regenerated by anyone,
on a laptop, without an A100 and without ImageNet — and it means every number on
a figure is traceable to a line in a JSON file rather than to something somebody
typed into a plotting script and never checked again.

Each figure is written twice, as <name>.svg and <name>-dark.svg, so a README can
serve the right one to each reader:

    <picture>
      <source media="(prefers-color-scheme: dark)" srcset="figures/name-dark.svg">
      <img src="figures/name.svg">
    </picture>

The light palette is the same one the rest of this work uses, so the light SVGs
drop straight into a site without restyling.

    python figures.py              # all of them
    python figures.py --only init  # one
"""

import argparse
import json
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import Rectangle

HERE = os.path.dirname(os.path.abspath(__file__))
RESULTS = os.path.join(HERE, "results")
FIGURES = os.path.join(HERE, "figures")

WIDTH_IN = 9.0
BODY = 9.0
TITLE = 13.0
LINE = 0.17
MARGIN = 0.38

LIGHT = dict(bg="#FBF9F4", ink="#0F172A", muted="#5B6762", rule="#D9D3C4",
             accent="#371E77", accent2="#4B28A4", warn="#D3542A",
             good="#4F7357", fill="#EFEADF")
DARK = dict(bg="#0D1117", ink="#E6EDF3", muted="#8B949E", rule="#30363D",
            accent="#A78BFA", accent2="#8B7BE8", warn="#FF7B5A",
            good="#7EE2A8", fill="#161B22")

FAMILY = "Inter" if any(f.name == "Inter" for f in
                        matplotlib.font_manager.fontManager.ttflist) else "DejaVu Sans"


class Sheet:
    """A figure whose vertical cursor runs in inches from the top.

    Spacing written as axis fractions changes meaning when the figure height
    changes, which is how a subtitle ends up sitting on the title above it.
    Inches do not.
    """

    def __init__(self, height_in, pal):
        self.h, self.p = height_in, pal
        self.fig = plt.figure(figsize=(WIDTH_IN, height_in))
        self.ax = self.fig.add_axes([0, 0, 1, 1])
        self.ax.set_xlim(0, WIDTH_IN); self.ax.set_ylim(0, height_in); self.ax.axis("off")
        self.ax.add_patch(Rectangle((0, 0), WIDTH_IN, height_in,
                                    facecolor=pal["bg"], edgecolor="none", zorder=-10))
        self.y = 0.34
        self.L, self.R = MARGIN, WIDTH_IN - MARGIN

    def _yy(self, y=None):
        return self.h - (self.y if y is None else y)

    def text(self, x, s, size=BODY, colour=None, weight="normal",
             ha="left", va="top", y=None):
        self.ax.text(x, self._yy(y), s, fontsize=size,
                     color=colour or self.p["ink"], fontweight=weight, ha=ha, va=va)

    def head(self, number, label, title, subtitle=None):
        self.text(self.L, f"{number}  /  {label}", colour=self.p["accent"], weight="bold")
        self.y += 0.235
        self.text(self.L, title, size=TITLE, weight="bold")
        self.y += 0.265
        if subtitle:
            self.text(self.L, subtitle, colour=self.p["muted"])
            self.y += 0.22

    def note(self, lines):
        for line in lines:
            self.text(self.L, line, colour=self.p["muted"])
            self.y += LINE

    def rule(self):
        self.ax.plot([self.L, self.R], [self._yy()] * 2,
                     color=self.p["rule"], lw=0.9, zorder=0)
        self.y += 0.02

    def box(self, x, w, h, **kw):
        self.ax.add_patch(Rectangle((x, self._yy(self.y + h)), w, h, **kw))

    def save(self, name):
        over = self.y > self.h - 0.15
        suffix = "-dark" if self.p is DARK else ""
        path = os.path.join(FIGURES, f"{name}{suffix}.svg")
        self.fig.savefig(path, format="svg")        # never bbox_inches: it rescales
        plt.close(self.fig)
        if over:
            print(f"   !! {name}{suffix}: content ends at {self.y:.2f} of {self.h:.2f} in")
        return not over


def load(name):
    return json.load(open(os.path.join(RESULTS, name + ".json")))


