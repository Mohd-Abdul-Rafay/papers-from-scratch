def fig_conversion(pal):
    a = load("architecture")
    c, sm = a["conversion"], a["score_map"]
    s = Sheet(6.35, pal)
    s.head("01", "SECTION 3.2",
           "One layer wanted 224. Rewrite it as a convolution and the number disappears",
           "the conversion moves no numbers — it only reshapes them")
    s.y += 0.12

    for name, shape, col in [("nn.Linear(25088, 4096)", c["linear_weight_shape"], pal["accent2"]),
                             ("nn.Conv2d(512, 4096, k=7)", c["conv_weight_shape"], pal["accent"])]:
        s.box(s.L, 2.45, 0.28, facecolor=col, edgecolor="none")
        s.text(s.L + 0.12, name, colour=pal["bg"], weight="bold", y=s.y + 0.085)
        s.text(3.10, "weight " + str(tuple(shape)).replace(" ", ""), y=s.y + 0.085)
        s.text(s.R, f"{c['values']:,} values", colour=pal["muted"], ha="right",
               y=s.y + 0.085)
        s.y += 0.42

    s.y += 0.04
    s.text(s.L, "512 × 7 × 7  =  25,088", colour=pal["muted"], y=s.y + 0.08)
    s.box(4.30, 3.82, 0.32, facecolor=pal["fill"], edgecolor=pal["good"], lw=1.1)
    s.text(6.21, f"the two networks agree to "
                 f"{c['max_abs_difference_pretrained']:.1e}",
           colour=pal["good"], weight="bold", ha="center", y=s.y + 0.09)
    s.y += 0.50
    s.note([
        "One to two units in the last place of float32 — a matrix multiply and a convolution "
        "accumulate in different",
        "orders, so exactly zero would be the suspicious answer. The .view() is legal only "
        "because the flatten feeding",
        "the Linear layer runs in C order; under any other order it would succeed and "
        "silently scramble the weights.",
    ])

    s.y += 0.14; s.rule(); s.y += 0.20
    s.head("02", "THE SCORE MAP", "One prediction becomes a map over positions",
           "stride 32, so each position is a 224 window offset 32 pixels from the last")
    s.y += 0.10

    cell, gap = 0.072, 0.012
    base = s.y + 0.86
    for i, case in enumerate(sm[:5]):
        (hh, ww), (mh, mw) = case["input"], case["map"]
        cx = s.L + i * 1.63
        start = len(s.ax.patches)
        for r in range(mh):
            for cc in range(mw):
                s.box(cx + cc * (cell + gap), cell, cell,
                      facecolor=pal["accent"] if mh * mw > 1 else pal["warn"],
                      edgecolor="none")
        for k, patch in enumerate(s.ax.patches[start:]):
            r, cc = divmod(k, mw)
            patch.set_xy((cx + cc * (cell + gap),
                          s.h - (base - (mh - 1 - r) * (cell + gap))))
        s.text(cx, f"{hh} × {ww}", weight="bold", y=base + 0.18)
        s.text(cx, f"{mh} × {mw}  =  {case['positions']}", colour=pal["muted"],
               y=base + 0.36)

    s.y = base + 0.60
    s.note([
        "At 224 the map is a single position, in rust: dense evaluation there IS the "
        "original network. Every size was",
        "predicted from (side // 32 − 6) before being measured, and all of them matched. "
        "Real images are not square.",
    ])
    return s.save("conversion")


