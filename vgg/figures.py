def fig_init(pal):
    d = load("init_study")
    h, sd = d["heatmap"], d["signal_deficit"]
    s = Sheet(6.92, pal)
    s.head("01", "SECTION 3.1, MEASURED",
           "Only one initialisation trains configuration E at all",
           f"Imagenette, {h['epochs']} epochs, validation accuracy · chance is {h['chance_pct']}%")
    s.y += 0.12

    x0, cw = 2.55, 1.12
    for j, lr in enumerate(h["learning_rates"]):
        s.text(x0 + j * cw + cw / 2, f"{lr:g}", colour=pal["muted"], ha="center")
    s.text(x0 + 2.5 * cw, "learning rate", colour=pal["muted"], ha="center", y=s.y - 0.20)
    s.y += 0.24

    for row in h["rows"]:
        s.text(s.L, row["init"], va="center", y=s.y + 0.145)
        for j, acc in enumerate(row["acc"]):
            nan = row["nan"][j]
            trains = (not nan) and acc > 2 * h["chance_pct"]
            s.box(x0 + j * cw, cw * 0.90, 0.29,
                  facecolor=pal["good"] if trains else pal["fill"],
                  edgecolor=pal["warn"] if nan else "none", lw=1.3)
            s.text(x0 + j * cw + cw * 0.45, "NaN" if nan else f"{acc:.1f}",
                   colour=pal["bg"] if trains else (pal["warn"] if nan else pal["muted"]),
                   weight="bold" if trains or nan else "normal",
                   ha="center", va="center", y=s.y + 0.145)
        s.y += 0.355

    s.y += 0.10
    s.note([
        f"{h['summary']['cells_that_train']} cells train, "
        f"{h['summary']['cells_near_chance']} sit at chance, "
        f"{h['summary']['cells_diverged']} diverge. Kaiming's window has two different edges: at "
        f"1e-2 the network",
        "settles at chance, and from 3e-2 upward it blows up. Depth narrows the window from "
        "both sides at once.",
    ])

    s.y += 0.14; s.rule(); s.y += 0.20
    s.head("02", "WHY, AND WHY PRE-INITIALISATION WORKS",
           "The shortfall compounds over depth",
           "modelled deficit against Kaiming, with the measured accuracy beside it")
    s.y += 0.08

    bars = sd["bars"][:4]
    import math
    top = math.log10(max(b["deficit"] for b in bars))
    for b in bars:
        s.text(s.L, f"{b['case']}", weight="bold", va="center", y=s.y + 0.065)
        s.text(s.L, f"{b['init']}, {b['layers']} layers", colour=pal["muted"],
               va="center", y=s.y + 0.215)
        w = math.log10(b["deficit"]) / top * 3.30
        good = b["measured_val_acc"] > 2 * h["chance_pct"]
        s.box(2.70, w, 0.13, facecolor=pal["accent"], edgecolor="none")
        s.text(2.70 + w + 0.10, f"{b['deficit']:,}x", weight="bold", va="center",
               y=s.y + 0.065)
        s.text(s.R, f"{b['measured_val_acc']}%", ha="right", va="center",
               colour=pal["good"] if good else pal["muted"],
               weight="bold" if good else "normal", y=s.y + 0.065)
        s.y += 0.355

    s.y += 0.06
    ck = sd["checked_against_measurement"]
    s.note([
        "Glorot gives half Kaiming's variance per layer, so the shortfall compounds as a "
        "power of the depth. Over 8",
        "layers that is survivable; over 16 it is not. The paper's transplant removes four "
        "bad layers and four is enough.",
        f"Bars are MODELLED. One has been checked: for E alone the model gives "
        f"{ck['modelled_deficit']}x and the measured activation",
        f"RMS ratio was {ck['measured_activation_rms_ratio_at_last_conv']:,}x, "
        f"{ck['factor_off']}x larger. Read the axis as an ordering, not a quantity.",
    ])
    return s.save("init")


